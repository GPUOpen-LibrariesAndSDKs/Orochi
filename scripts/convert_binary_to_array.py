"""Convert a binary file to a C/C++ byte array header.

Supports optional Zstd compression metadata. Generates a header with
the binary data as a const unsigned char array plus size constants.

Usage:
    python3 convert_binary_to_array.py <input_before_compression> <input_after_compression> <output_header> <ON|OFF>
"""
import sys
from pathlib import Path


def binary_to_c_array(bin_file, array_name, size_before_compression, is_compressed):
    """Read a binary file and generate a C array declaration string."""
    with open(bin_file, 'rb') as f:
        binary_data = f.read()

    hex_array = ', '.join(f'0x{b:02x}' for b in binary_data)
    lines = [
        f'const unsigned char {array_name}[] = {{\n    {hex_array}\n}};',
        f'const size_t {array_name}_size = sizeof({array_name}); // {len(binary_data)}',
    ]

    if is_compressed:
        lines.append(
            f'const size_t {array_name}_size_uncompressed = {size_before_compression}; '
            f'// size of the data in bytes, once it has been uncompressed.'
        )
    else:
        lines.append(
            f'const size_t {array_name}_size_uncompressed = {array_name}_size; '
            f'// same as raw buffer, because data is not compressed.'
        )

    lines.append(f'const bool   {array_name}_isCompressed = {"true" if is_compressed else "false"};')

    return '\n'.join(lines) + '\n'


def main():
    if len(sys.argv) != 5:
        print(
            f"Usage: {sys.argv[0]} <input_before_compression> "
            f"<input_after_compression> <output_header> <ON|OFF>",
            file=sys.stderr
        )
        sys.exit(1)

    bin_file_before = sys.argv[1]
    bin_file_after = sys.argv[2]
    header_file_path = sys.argv[3]
    is_compressed = sys.argv[4].upper() == "ON"

    header_file = Path(header_file_path).name
    array_name = header_file.replace('.', '_')

    if not is_compressed:
        bin_file_after = bin_file_before

    size_before = Path(bin_file_before).stat().st_size
    c_array = binary_to_c_array(bin_file_after, array_name, size_before, is_compressed)

    with open(header_file_path, 'w') as f:
        f.write("// generated by convert_binary_to_array.py\n")
        if is_compressed:
            f.write("// Data is compressed.\n")
        f.write(c_array)


if __name__ == "__main__":
    main()
